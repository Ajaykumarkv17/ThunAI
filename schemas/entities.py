"""Entity models persisted to State_Store / Audit_Ledger.

Implements ``Incident``, ``Responder``, ``Shelter``, ``EscalationRecord``,
``EscalationOption``, and ``AuditEntry`` per design.md §4.2.

Verification note (Req 19.8 / task 2.2 "verify first"): Pydantic v2 constraint
syntax was confirmed against the current Pydantic docs before writing these
models — numeric bounds use ``Field(ge=..., le=...)`` (inclusive bounds),
string length bounds use ``Field(max_length=..., min_length=...)``, and closed
choice sets use ``typing.Literal`` rather than a plain ``str`` + validator.
This matches ``pydantic==2.13.5`` as pinned in ``requirements.txt``.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

__all__ = [
    "Incident",
    "Responder",
    "Shelter",
    "EscalationOption",
    "EscalationRecord",
    "AuditEntry",
]


# ---------------------------------------------------------------------------
# Human-readable helpers used by EscalationRecord.template_fields()
# ---------------------------------------------------------------------------


def _to_local(iso_timestamp: str) -> str:
    """Render an ISO-8601 (with timezone) response deadline as a short local
    "HH:MM" string for the hand-authored notification templates (design.md
    §3.5). Never calls a model — purely mechanical formatting of a persisted
    field, per Req 11.3 ("no field generated by a model invocation").
    """
    # Accept "...T14:52:00+05:30" / "...T14:52:00Z" and similar ISO variants.
    from datetime import datetime

    try:
        dt = datetime.fromisoformat(iso_timestamp.replace("Z", "+00:00"))
        return dt.strftime("%H:%M")
    except ValueError:
        # Fall back to the raw string rather than raising — template
        # rendering must never fail on an unexpected but non-empty value.
        return iso_timestamp


def _humanize(action_key: str) -> str:
    """Turn a machine default-action key (e.g. ``"hold_assignment"``) into the
    short human phrase the templates in design.md §3.5 interpolate
    (e.g. "hold the assignment and keep searching for capacity").
    """
    _KNOWN: dict[str, str] = {
        "hold": "hold (nothing is sent by default)",
        "hold_assignment": "hold the assignment and keep searching for capacity",
        "send_with_standard_wording": "send with standard wording",
        "pay_now": "pay now",
        "close_request": "close the request",
    }
    if action_key in _KNOWN:
        return _KNOWN[action_key]
    # Fallback: turn "some_action_key" into "some action key".
    return action_key.replace("_", " ")


